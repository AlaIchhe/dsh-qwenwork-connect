import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(rootDir, 'dist');

const HOST_EXTERNALS = [
  '@deepseek-ai/*',
  'node:*',
  'zod',
];

async function build() {
  await fs.rm(distDir, { recursive: true, force: true });

  await Promise.all([
    // 1. Host plugin entry
    esbuild.build({
      entryPoints: [path.join(rootDir, 'src/host/index.ts')],
      outfile: path.join(distDir, 'host/index.js'),
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node22',
      external: HOST_EXTERNALS,
      sourcemap: true,
      logLevel: 'info',
    }),

    // 2. Standalone core protocol library
    esbuild.build({
      entryPoints: [path.join(rootDir, 'src/core/index.ts')],
      outfile: path.join(distDir, 'core/index.js'),
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node22',
      external: ['node:*'],
      sourcemap: true,
      logLevel: 'info',
    }),

    // 3. CLI entry
    esbuild.build({
      entryPoints: [path.join(rootDir, 'src/cli/login.ts')],
      outfile: path.join(distDir, 'cli/login.mjs'),
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node22',
      external: ['node:*'],
      banner: { js: '#!/usr/bin/env node' },
      sourcemap: true,
      logLevel: 'info',
    }),

    // 4. Client plugin entry wrapped in DSH __ModuleLoader__ envelope
    buildClient(),
  ]);

  await fs.chmod(path.join(distDir, 'cli/login.mjs'), 0o755);
}

async function buildClient() {
  const result = await esbuild.build({
    entryPoints: [path.join(rootDir, 'src/client/index.tsx')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime'],
    define: {
      'process.env.NODE_ENV': '"production"',
    },
    logLevel: 'info',
  });

  const code = result.outputFiles[0]?.text ?? '';
  const wrapped = [
    '// Generated by scripts/build.mjs — do not edit directly.',
    'window.__ModuleLoader__.load({',
    "  id: 'dsh-qwenwork-connect',",
    '  factory(require) {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    '    var __optionalRequire = function (id) { try { return require(id); } catch (_) { return undefined; } };',
    code,
    '    if (module.exports && typeof module.exports.__setOptionalRequire === "function") {',
    '      module.exports.__setOptionalRequire(__optionalRequire);',
    '    }',
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n');

  const outFile = path.join(distDir, 'client/index.js');
  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, wrapped, 'utf8');
}

build().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
